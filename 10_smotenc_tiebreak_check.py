"""Follow-up to 09 (Online Resource 1, analysis (viii)): does the tie rule of our SMOTE-NC explain its difference from
imbalanced-learn? The plan required that "an AUC difference larger than 0.005 is described and its cause investigated".

Our smote_nc sets each categorical value of a synthetic patient to the most frequent value among the base patient's k neighbors and
resolves ties in favor of the lowest level code (scipy.stats.mode), i.e. the reference level, which is the clinically favorable one
(stage IA, grade I, N0, M0, HR+/HER2-, no metastasis). imbalanced-learn breaks ties at random. Here the Zero + SMOTE-NC cell is
rebuilt as in the main run and the synthetic patients are generated by a copy of smote_nc that differs only in the tie rule
(random, from a separate random stream), so base patients, neighbors and interpolation points are identical to the main run.
Logistic regression, the classifier with the discrepancy, is refitted with the main run's seeds. The share of categorical values
equal to the reference level is compared between real minority patients, our synthetic patients, the random-tie variant and
imbalanced-learn. seer_modeling.py is not modified.

Run from this folder after 09_smotenc_crosscheck.py (README.md):  python 10_smotenc_tiebreak_check.py
"""
import re
import time
from pathlib import Path

import numpy as np
import pandas as pd
from imblearn.over_sampling import SMOTENC
from sklearn.neighbors import NearestNeighbors

import config
import seer_modeling as sm

DATA_ROOT = config.WORK_DIR
MODEL_DIR = DATA_ROOT / "outputs_modeling"
OUT_DIR = config.WORK_DIR / "outputs_smotenc_crosscheck"
CELL_INDEX = sm.CELLS.index(("zero", True))
NEW_CELL = "zero+randomties"


def smote_nc_random_ties(x_num, cat_codes, y, patient, rng, tie_rng, k=sm.SMOTE_K):
    """seer_modeling.smote_nc with one change: ties in the categorical vote are broken at random (tie_rng).

    Every draw from rng is the same as in smote_nc, so base patients, neighbors and gaps are identical.
    Also returns, per categorical predictor, the share of synthetic patients whose vote was tied.
    """
    minority = np.flatnonzero(y == 1)
    n_new = int((y == 0).sum() - minority.size)
    _, first, inverse = np.unique(patient[minority], return_index=True, return_inverse=True)
    rep = minority[first]
    u_num, u_cat = x_num[rep], cat_codes[rep]
    med = float(np.median(u_num.std(axis=0)))
    n_levels = cat_codes.max(axis=0).astype(int) + 1
    offsets = np.concatenate([[0], np.cumsum(n_levels)])
    cat_space = np.zeros((rep.size, int(offsets[-1])))
    for j in range(u_cat.shape[1]):
        cat_space[np.arange(rep.size), offsets[j] + u_cat[:, j]] = med / np.sqrt(2.0)
    space = np.hstack([u_num, cat_space])
    n_nb = min(k, rep.size - 1)
    idx = NearestNeighbors(n_neighbors=n_nb + 1).fit(space).kneighbors(space, return_distance=False)
    not_self = idx != np.arange(rep.size)[:, None]
    order = np.argsort(~not_self, axis=1, kind="stable")
    neighbors = np.take_along_axis(idx, order, axis=1)[:, :n_nb]

    vals = u_cat[neighbors]                                             # (n_rep, k, n_cat)
    counts = (vals[:, :, None, :] == vals[:, None, :, :]).sum(axis=2)    # how often each neighbor's value occurs
    is_max = counts == counts.max(axis=1, keepdims=True)
    first = np.take_along_axis(vals, is_max.argmax(axis=1)[:, None, :], axis=1)
    tied_rep = (is_max & (vals != first)).any(axis=1)                   # another value is equally frequent
    key = counts + 0.5 * tie_rng.random(counts.shape)                   # random choice among the most frequent values
    modes = np.take_along_axis(vals, key.argmax(axis=1)[:, None, :], axis=1)[:, 0, :].astype(cat_codes.dtype)

    base = inverse[rng.integers(minority.size, size=n_new)]
    nb = neighbors[base, rng.integers(n_nb, size=n_new)]
    gap = rng.random((n_new, 1))
    new_num = u_num[base] + gap * (u_num[nb] - u_num[base])
    tied = tied_rep[base].mean(axis=0)
    return new_num, modes[base], tied


def run(data, r, k):
    saved = sm.load_split(MODEL_DIR, r, k)
    df, roles = data.cohort, sm.split_roles(data, r, k)
    idx = {role: np.flatnonzero(roles == role) for role in ("inner_train", "inner_val", "test")}
    outer = np.flatnonzero(roles != "test")
    enc = sm.Encoder(data, df.iloc[outer])
    X = {role: enc.full(df.iloc[rows]) for role, rows in idx.items()}
    x_num_it, codes_it = enc.numeric(df.iloc[idx["inner_train"]]), enc.cat_codes(df.iloc[idx["inner_train"]])
    x_out = np.vstack([X["inner_val"], X["test"]])
    out = saved[["row", "role", "w_36", "w_60", "w_120"]].copy()
    shares = []
    for tau in sm.HORIZONS:
        y_it = data.labels[f"y_{tau}"].to_numpy()[idx["inner_train"]]
        y_iv = data.labels[f"y_{tau}"].to_numpy()[idx["inner_val"]]
        labels = (y_it == 1).astype(int)
        rng = np.random.default_rng([sm.SEED, r, k, tau, CELL_INDEX])
        tie_rng = np.random.default_rng([sm.SEED, r, k, tau, CELL_INDEX, 2])
        new_num, new_cat, tied = smote_nc_random_ties(x_num_it, codes_it, labels, np.arange(labels.size), rng, tie_rng)
        Xr = np.vstack([X["inner_train"], np.hstack([new_num, enc.onehot_from_codes(new_cat)])])
        yr = np.concatenate([labels, np.ones(new_num.shape[0], dtype=int)])
        v_rows, y_val, w_val = sm.cell_rows("zero", y_iv, np.ones(y_iv.size))
        seed = int(rng.integers(2**31 - 1))                              # the logistic regression seed of the main run
        model, _ = sm.fit_classifier("lr", Xr, yr, np.ones(yr.size), X["inner_val"][v_rows], y_val, w_val, seed)
        out[sm.pred_column("lr", NEW_CELL, tau)] = model.predict_proba(x_out)[:, 1].astype(np.float32)
        # reference-level shares: real minority patients and the three synthetic samples
        rng_ours = np.random.default_rng([sm.SEED, r, k, tau, CELL_INDEX])
        _, ours_cat = sm.smote_nc(x_num_it, codes_it, labels, np.arange(labels.size), rng_ours)
        imb_seed = int(np.random.default_rng([sm.SEED, r, k, tau, CELL_INDEX, 1]).integers(2**31 - 1))   # as in 09
        x_in = np.hstack([x_num_it, codes_it.astype(np.float64)])
        x_res, _ = SMOTENC(categorical_features=list(range(x_num_it.shape[1], x_in.shape[1])), k_neighbors=sm.SMOTE_K,
                           sampling_strategy=1.0, random_state=imb_seed).fit_resample(x_in, labels)
        imb_cat = np.rint(x_res[labels.size:, x_num_it.shape[1]:]).astype(codes_it.dtype)
        for name, cat in [("real minority", codes_it[labels == 1]), ("ours", ours_cat), ("random ties", new_cat),
                          ("imbalanced-learn", imb_cat)]:
            shares.append({"repeat": r, "fold": k, "tau": tau, "sample": name,
                           "share_reference_level": float((cat == 0).mean()),
                           **{f"ref_{c}": float((cat[:, j] == 0).mean()) for j, c in enumerate(enc.cat_cols)}})
        shares.append({"repeat": r, "fold": k, "tau": tau, "sample": "tied votes (share of synthetic values)",
                       "share_reference_level": float(tied.mean()),
                       **{f"ref_{c}": float(tied[j]) for j, c in enumerate(enc.cat_cols)}})
    frame = pd.concat([out, saved[[c for c in saved.columns if re.match(r"^lr\|(zero|zero\+smote)\|", c)]]], axis=1)
    xc = pd.read_parquet(OUT_DIR / f"split_r{r}_k{k}.parquet")
    frame = pd.concat([frame, xc[[c for c in xc.columns if c.startswith("lr|zero+imblearn|")]]], axis=1)
    return sm.evaluate_split(frame, data, r, k), pd.DataFrame(shares)


def main():
    data = sm.load_prep(DATA_ROOT / "outputs_model_prep")
    splits = sorted((int(m[1]), int(m[2])) for m in
                    (re.match(r"split_r(\d+)_k(\d+)\.parquet", p.name) for p in MODEL_DIR.glob("split_r*_k*.parquet")) if m)
    mets, shares = [], []
    for r, k in splits:
        t0 = time.time()
        met, sh = run(data, r, k)
        mets.append(met); shares.append(sh)
        print(f"split ({r},{k}) done in {time.time() - t0:.0f}s", flush=True)
    met, sh = pd.concat(mets, ignore_index=True), pd.concat(shares, ignore_index=True)
    met.to_csv(OUT_DIR / "tiebreak_metrics_by_split.csv", index=False)
    sh.to_csv(OUT_DIR / "tiebreak_reference_level_shares.csv", index=False)
    rows = []
    for metric in ["brier", "auc", "precision", "oe_ratio"]:
        for name, a, b in [("random ties - ours", NEW_CELL, "zero+smote"), ("imblearn - random ties", "zero+imblearn", NEW_CELL),
                           ("imblearn - ours", "zero+imblearn", "zero+smote")]:
            for tau in sm.HORIZONS:
                sel = met[met.tau == tau]
                x = sel[sel.cell == a].sort_values(["repeat", "fold"])[metric].to_numpy()
                y = sel[sel.cell == b].sort_values(["repeat", "fold"])[metric].to_numpy()
                rows.append({"metric": metric, "contrast": name, "tau": tau, **sm.corrected_ttest(x - y)})
    con = pd.DataFrame(rows)
    con["p_holm"] = np.nan
    for _, g in con.groupby("metric").groups.items():
        con.loc[g, "p_holm"] = sm.holm_adjust(con.loc[g, "p_value"].to_numpy())
    con.to_csv(OUT_DIR / "tiebreak_contrasts.csv", index=False)
    print(met.groupby(["tau", "cell"])[["brier", "auc", "precision", "oe_ratio"]].mean().round(4).to_string())
    print(sh.groupby(["tau", "sample"])["share_reference_level"].mean().round(3).to_string())
    print(con.round(5).to_string())


if __name__ == "__main__":
    main()
